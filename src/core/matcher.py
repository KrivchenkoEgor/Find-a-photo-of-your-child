"""Сравнение лиц с эталоном. Процент — косинусное сходство, умноженное на 100.

Здесь нет порога отсечения: он живёт в интерфейсе и меняется мгновенно, потому что
лица уже посчитаны и лежат в памяти (и в оглавлении). Если бы порог участвовал в
расчёте, каждое движение ползунка запускало бы разбор папки заново.

Единственное число, похожее на порог, — `min_sim` в `make_reference`: оно решает,
какие дополнительные лица вообще попадут в эталон, и применяется один раз при
подтверждении фото пользователем, а не при каждой оценке. Окно эталона передаёт
`None` и тем самым выключает отбор: там решением стала галочка человека (задача T14).
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Sequence

import numpy as np

from .engine import Face, embeddings_of, prigoden_otpechatok, prigodnye_lica

REF_MIN_SIM = 0.40   # дефолт отбора дополнительных лиц; окно эталона зовёт сборку с None


@dataclass(frozen=True)
class Reference:
    embeddings: np.ndarray          # (k, 512), строки единичной длины

    @property
    def count(self) -> int:
        return int(self.embeddings.shape[0])


@dataclass(frozen=True)
class ScoredPhoto:
    percent: int
    similarity: float
    face: Face | None               # то лицо, которое дало максимум — его и рисуем
    # Номер СТРОКИ эталона, на которой максимум и достигнут (с единицы). `face` отвечает
    # на вопрос «какое лицо на снимке», этот номер — «по какому выбранному лицу нашли».
    # 0 означает «не считали»: пустой эталон или ни одного годного лица. Задача T15:
    # человек отмечает несколько примеров, среди них может стоять другой человек, и по
    # одному числу «45 %» эти два случая неотличимы.
    ref_lico: int = 0
    # Похожасть КАЖДОГО годного лица: (номер лица в присланном списке с единицы, процент).
    # Максимум одного лица для рамки мало: ребёнок стоит на групповом фото дважды, и
    # человек обязан увидеть обе рамки (задача T19, замер на архиве — лица 22 и 24 по 65 %).
    # Номера считаются по исходному списку, а не по очищенному, иначе битое лицо сдвинуло
    # бы рамку на чужое.
    po_licam: tuple[tuple[int, int], ...] = ()


def percent_of(similarity: float) -> int:
    """Сходство в проценты для показа. Отрицательное не показываем минусом.

    Непригодное число (NaN, Inf) даёт 0, а не исключение: `round(nan)` бросает
    ValueError, и одно испорченное лицо обрывало показ всего архива. Правило
    округления осталось прежним — `round` от брифа задачи 8; согласованность показа
    и отсечения ползунком решается в задачах 12 и 14, а не здесь.
    """
    if not bool(np.isfinite(similarity)):
        return 0
    return max(0, round(float(similarity) * 100))


def make_reference(anchor: Face, candidates: Sequence[Face],
                   min_sim: float | None = REF_MIN_SIM) -> Reference:
    """Образ от одного подтверждённого фото + похожие на него дополнительные эталоны.

    Anchor попадает в эталон всегда: пользователь подтвердил именно это фото, и
    пустой эталон означал бы «приложение потеряло то, что просили». Единственное
    исключение — anchor с непригодным отпечатком: из него эталона не выходит вовсе,
    и молча вернуть пустой образ было бы тем самым «потеряли» без единого сообщения.
    Здесь громкая ошибка честнее тихого нуля (строки оглавления под защитой:
    `Face.from_dict` непригодное лицо не возвращает).

    `min_sim=None` выключает отбор по сходству: в эталон берётся любой годный
    кандидат. Этим способом окно эталона зовёт сборку с задачи T14 — отмеченное
    человеком лицо участвует в поиске, а низкое число сходства стало предупреждением,
    а не запретом. Дефолт остаётся `REF_MIN_SIM`: боевой прогон архива и сборка
    эталона «по одному подтверждённому фото» продолжают не пускать в эталон чужие
    лица, и тест `tests/test_matcher.py` сторожит именно это число.

    Непригодный отпечаток не участвует ни при каком значении — при `None` тоже:
    фильтрует `prigodnye_lica`, потому что таким вектором буквально нечем считать.

    Кластеризация всех лиц между собой хуже: детские лица в разном освещении
    расходятся сильнее взрослых, группы рвутся и склеиваются — на проверенном
    архиве так к нужному ребёнку прицеплялся другой.
    """
    if not prigoden_otpechatok(anchor.embedding):
        raise ValueError(
            "отпечаток эталонного лица непригоден к сравнению: подтвердите другое фото")
    keep = [anchor]
    for cand in prigodnye_lica(candidates):
        if cand is anchor:
            continue
        if min_sim is None or float(cand.embedding @ anchor.embedding) >= min_sim:
            keep.append(cand)
    return Reference(embeddings_of(keep))


def score_photo(faces: Sequence[Face], ref: Reference) -> ScoredPhoto:
    """Насколько фото похоже на эталон: максимум по всем лицам и всем строкам эталона.

    Максимум берётся по обоим измерениям. По лицам — потому что на снимке может быть
    толпа, и ребёнок обязан найтись даже среди чужих лиц. По строкам эталона —
    потому что одно и то же лицо в другом ракурсе ближе к одному из добавленных
    отпечатков, чем к anchor.

    Непригодные отпечатки не участвуют ни в выборе, ни в показе: строка с NaN
    выиграла бы `argmax` (NaN сравним как угодно, и `round(nan)` падает), а вектор
    чужой ширины ронял бы `matmul`. Отсюда два следствия: список лиц сначала
    прогоняется через `prigodnye_lica` — иначе номер строки матрицы не соответствовал
    бы номеру лица, — и максимум считается только по конечным числам. Ни один исход
    здесь не исключение: битое лицо это «этого лица нет», а не сорванный прогон.

    Номер строки эталона (`ref_lico`) берётся из ТОГО ЖЕ очищенного массива, что и
    максимум, — из `max(axis=1)` он терялся. Своя цена — второй `argmax` по одной
    строке, то есть микросекунды: замер на архиве проекта, 591 лицо против эталона из
    16 лиц, — 4,9 мс против 5,8 мс при одном лице, а всё долгое время (чтение файла и
    детекция) платится один раз за снимок независимо от числа выбранных лиц. Поэтому
    здесь не может быть и оптимизации «хватит и первой строки»: она сделала бы число на
    карточке заниженным, а человек принял бы по нему решение.

    Кроме максимума возвращается `po_licam` — похожесть каждого годного лица. Одного
    максимума не хватает на групповом фото: ребёнок стоит в кадре дважды, и человек
    обязан увидеть рамку на обоих лицах, а не на том, что оказался чуть похожее
    (задача T19).
    """
    usable = prigodnye_lica(faces)
    if not usable or ref.count == 0:
        return ScoredPhoto(percent=0, similarity=0.0, face=None)
    sims = embeddings_of(usable) @ ref.embeddings.T       # (n_лица, k_эталоны)
    chistye = np.where(np.isfinite(sims), sims, -np.inf)
    per_face = chistye.max(axis=1)
    if not bool(np.isfinite(per_face).any()):
        # Все строки эталона непригодны — сравнить не с чем, но это ноль, а не падение.
        return ScoredPhoto(percent=0, similarity=0.0, face=None)
    k = int(per_face.argmax())
    # `chistye[k]`, а не `sims[k]`: у массива с NaN `argmax` отдаёт индекс NaN, а не
    # индекс наибольшего конечного — отравленная первая строка выиграла бы номер.
    j = int(chistye[k].argmax()) + 1
    best = float(per_face[k])
    # Номера лиц — по ПРИСЛАННОМУ списку, а не по очищенному: `prigodnye_lica` сохраняет
    # порядок, поэтому позиция восстанавливается сравнением объектов. По координатам
    # нельзя: у двух лиц в кадре рамка вполне может быть одинаковой, и рамка уехала бы
    # на чужое лицо.
    godnye = {id(lic) for lic in usable}
    po_licam = tuple(zip((i for i, lic in enumerate(faces, 1) if id(lic) in godnye),
                         (percent_of(float(s)) for s in per_face)))
    return ScoredPhoto(percent=percent_of(best), similarity=best, face=usable[k],
                       ref_lico=j, po_licam=po_licam)
