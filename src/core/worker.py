class OglavlenieNedostupno(RuntimeError):
    """Оглавление перестало отвечать. Часть папки уже разобрана и лежит в нём.

    Это не «файл не читается» и не «модель упала на кадре»: встаёт весь прогон, и
    врать про него нельзя дважды. Первый раз — если назвать эту беду неудачной
    загрузкой моделей: пользователь с полным диском будет искать сломанные веса.
    Второй раз — если промолчать о снятом: лица до сбоя переживают его в базе, и
    следующий запуск продолжает с этого места, а не перечитывает архив заново.
    """

    def __init__(self, prichina: str, sohraneno: int = 0) -> None:
        self.prichina = prichina
        self.sohraneno = max(0, int(sohraneno))
        if self.sohraneno:
            itog = (f"уже снятые лица сохранены — {self.sohraneno} "
                    f"{_mnohozhechestvo(self.sohraneno, 'снимок', 'снимка', 'снимков')} "
                    "в оглавлении, следующий запуск продолжит с этого места, а не "
                    "начнёт заново")
        else:
            itog = ("ни один снимок ещё не разобран и не потерян — после починки "
                    "разберите папку заново")
        super().__init__(f"оглавление недоступно: {prichina}; {itog}.")


@dataclass
class ScanStats:
    """Сводка разбора. Числа для полоски прогресса и для отчёта, а не для отладки.

    Поля потерь (`failures`, `dropped_faces`, `cache_damage`) разделены намеренно:
    это три разных разговора с пользователем. «Файл не читается» — приложение тут
    бессильно. «Лицо отброшено как непригодное» — тоже, но сам снимок разобран и
    больше не читается. «Оглавление починено» — про старую версию приложения: оно
    проходит само после первого же пересчёта.

    Причина в `failures` — не ярлык, а зацепка для отчёта (задача 10): у неё есть
    продолжение после «файл не читается: », и на нём гнилой HEIC отличается от
    обрезанного JPEG. См. `_pochemu_ne_chitaetsya`.
    """

    scanned: int = 0          # сколько фото обработано сейчас моделями
    cached: int = 0           # сколько взято из оглавления
    seconds: float = 0.0
    failures: list[tuple[str, str]] = field(default_factory=list)
    # Лица, отброшенные как непригодные, — по файлам, где это случилось. Фото при этом
    # разобрано и лежит в оглавлении: теряется лицо, а не снимок.
    #
    # Сюда попадают и снимки, взятые из оглавления: число потерь записано в саму строку
    # оглавления, потому что оглавление — единственная память, переживающая запуск.
    # Модель тёплому прогону про этот снимок не сказала бы ничего, и отчёт соврал бы
    # «потерь нет» об архив, где лица уже теряли.
    dropped_faces: dict[Path, int] = field(default_factory=dict)
    # Сколько строк оглавления пришлось выбросить как повреждённые (счётчик FaceCache
    # на момент разбора). Такие фото пересчитаны моделями заново — это починка, а не
    # потеря, и путать её с `dropped_faces` нельзя.
    cache_damage: int = 0


def obespechit_zagruzku(engine: FaceEngine) -> None:
    """Загрузить модели ровно один раз за сессию, сколько бы прогонов ни было.

    Зачем не просто `engine.load()`: `load()` стоит 13–21 с, а на живом `BothEngine`
    второй вызов ещё и гарантированно падает — юнет после загрузки отказывается
    принимать распознаватель, и пользователь видел бы сообщение, которое не может ни
    понять, ни применить.

    Признак готовности спрашиваем через `getattr`, а по умолчанию верим в «не готово»:
    чужой движок без поля `loaded` получит `load()` перед каждым прогоном — медленно,
    но безопасно. Обратный запас («считать готовым») дал бы `RuntimeError: модели не
    загружены` на первом же снимке. Все три движка проекта это поле носят, и тест
    `test_tri_realnyh_dvizhka_soblyudayut_kontrakt_loaded` следит, чтобы так и осталось
    — в том числе за тем, что `loaded` не врет о половинчатой загрузке: поверив
    «готово» там, где поднялась только одна модель, эта функция больше никогда не
    попробует загрузить вторую, и весь архив умрёт на первом же кадре.

    Интерфейс может вызвать эту функцию заранее, до запуска потока (задача 15), —
    повторный вызов из рабочего потока ничего не стоит.
    """
    with _zagruzochnyy_zamok:
        if getattr(engine, "loaded", False):
            return
        engine.load()


def _schet_otsortirovannyh(engine: FaceEngine) -> int:
    """Сколько лиц движок отбросил сам, как непригодные.

    `detect()` отдаёт список лиц, и число потерь положить в него некуда, а менять
    сигнатуру ради счётчика — значит переписывать три движка и их тесты. Поэтому
    договорённость мягкая: движок, которому есть что сказать, носит накопительный
    счётчик `otsortirovannye_lica` (все три движка проекта его носят), а молчаливый
    отдаёт 0. Потери видны всё равно: свой фильтр `_razobrat_foto` считает обязательно.
    """
    return int(getattr(engine, "otsortirovannye_lica", 0))


def _pochemu_ne_chitaetsya(path: Path) -> str:
    """Почему снимок не открылся — текст исключения из Pillow.

    `load_photo` держит обещание «верни None, не падай» (оно покрыто тестами задачи 3,
    и пакетный прогон без окна тоже на него опирается), поэтому причина гибнет там,
    где её уже не достать. Достаём её здесь, второй попыткой открыть файл: платим одной
    лишней декодировкой и только за тот снимок, который уже потерян.

    Повтор — не косметика, а единственный способ различить беды. «Не опознан формат»
    (битый JPEG, чужое расширение), «поток обрезан» (недокачался из iCloud) и «контейнер
    цел, а декодер споткнулся» (кривый HEIC с iPhone) — это три разных разговора с
    человеком, который принёс папку с телефона. Одна строка «файл не читается» на
    сотнях снимков не даёт ни одной зацепки.

    HEIC здесь открывается потому, что импорт `.scanner` выше уже вызвал
    `register_heif_opener()`: список открывателей форматов у Pillow общий на процесс.
    """
    try:
        with Image.open(path) as im:
            im.load()                       # гнилые данные всплывают на декодировке
    except Exception as exc:
        # Pillow вставляет полный путь, а он уже лежит в первом поле `failures`:
        # в отчёте имя файла два раза подряд только мешает читать.
        return f"{type(exc).__name__}: {exc}".replace(str(path), path.name)
    return ("кадр декодируется, но в изображение нужного формата не превращается "
            "(проверьте режим цвета)")


def _operaciya_s_oglavleniem(deystvie: Callable[[], _T], stats: ScanStats) -> _T:
    """Вызвать операцию оглавления, переведя сбой базы в именованную беду прогона.

    Ловим всё подряд, а не только `sqlite3.Error`: SQLite бросает и `OperationalError`
    (место кончилось, база заблокирована), и `DatabaseError` (диск не отвечает, файл
    повреждён), а бывает, что долетает и `OSError` — диск успевают вытащить. Тип сам по
    себе ничего не решает; решает ответ на вопрос «что уже сохранено», а его знает
    только сводка разбора.

    В `failures` это прятать нельзя: там лежит испорченный *снимок*, а тут встаёт вся
    папка, и продолжение прогона только соврало бы отчёту.

    Сохранённым считаем и свежий разбор, и попадание в оглавление — `stats.scanned +
    stats.cached`, оба исхода означают, что снимок в базе лежит. По одному `scanned`
    папка, половина которой была разобрана прошлым запуском, при сбое на второй
    половине получила бы честное «ни один снимок ещё не разобран»: занижение ровно
    там, где человеку важнее всего знать, что труд не потерян.
    """
    try:
        return deystvie()
    except OglavlenieNedostupno:
        raise
    except Exception as exc:
        raise OglavlenieNedostupno(_obyasni_sbboy_oglavleniya(exc),
                                   sohraneno=stats.scanned + stats.cached) from exc


def _razobrat_foto(path: Path, engine: FaceEngine, cache: FaceCache, max_dim: int,
                   stats: ScanStats) -> list[Face] | None:
    """Один снимок до конца: прочитать, найти лица, отбросить непригодные, записать.

    `None` — фото не обработано; причина уже лежит в `stats.failures`. Исходы, где
    снимок обработан (`cached`, `scanned`, `dropped_faces`), считаются здесь же —
    это единственное место, где известно, чем именно он был.

    Непригодные отпечатки отсекаются здесь, хотя движки делают то же самое внутри
    `detect()`. Не для красоты: оглавление — единственный путь, где лицо переживает
    перезапуск приложения, а `Face.from_dict` на строке с NaN бросает ValueError.
    Запиши мы такое лицо — снимок оказывался бы битым, удалялся бы и перечитывался
    моделями на каждом прогоне до конца жизни архива, молча и бесконечно.

    В `dropped_faces` складываются обе отбраковки: и та, что увидели движки внутри
    `detect()` (см. `_schet_otsortirovannyh`), и та, что видим мы здесь. Иначе
    «лицо отброшено как непригодное» в отчёте значило бы «повезло, движок доложил».

    Наружу исключение не уходит только там, где оно штатное: битый файл и упавшая
    модель. Сбой самой базы — это ЧП всего разбора, и он уходит наверх через
    `OglavlenieNedostupno` (см. `_operaciya_s_oglavleniem`): проглотить его значило бы
    сделать вид, что папка разобрана, хотя с этого места она не двигается.
    """
    try:
        stamp = file_stamp(path)
    except OSError as exc:                       # снимок успели удалить или переместить
        stats.failures.append((str(path), f"файл недоступен: {exc}"))
        return None

    cached = _operaciya_s_oglavleniem(
        lambda: cache.get_s_poterjami(path, stamp, engine.name, max_dim), stats)
    if cached is not None:
        # Пустой список — попадание, а не промах: сведём проверку к истинности, и фото
        # без лиц снова читался бы моделями на каждом прогоне.
        lica, otkuda_progon = cached
        stats.cached += 1
        if otkuda_progon:
            # Потери прошлого прогона живут в оглавлении: сюда модели не заглядывали
            # вовсе и сказать про этот снимок нечего. Без этой строки тёплый прогон
            # печатал бы «потерь нет» об архив, в котором лица уже теряли.
            stats.dropped_faces[path] = otkuda_progon
        return lica

    image = load_photo(path, max_dim=max_dim)
    if image is None:
        # Причина дописывается сюда, а не возвращается из `load_photo`: тот модуль
        # обещает не бросать, и отчёт без зацепки «почему именно» нерабочий.
        stats.failures.append(
            (str(path), f"файл не читается: {_pochemu_ne_chitaetsya(path)}"))
        return None
    schet_do = _schet_otsortirovannyh(engine)
    try:
        naidennye = engine.detect(image)
    except Exception as exc:                     # движок падает на одном кадре — не на папке
        stats.failures.append((str(path), f"ошибка распознавания: {exc}"))
        return None
    # Прирост за этот кадр: счётчик движка накопительный и переживает не один снимок.
    otsortirovano = max(0, _schet_otsortirovannyh(engine) - schet_do)

    lica = [f for f in naidennye if prigoden_otpechatok(f.embedding)]
    otsortirovano += len(naidennye) - len(lica)
    if otsortirovano > 0:
        stats.dropped_faces[path] = otsortirovano
    # Число потерь едет В СТРОКУ оглавления, а не только в сводку прогона: следующий
    # тёплый запуск этот снимок моделями не прочитает и иначе не узнает, что на нём
    # было что терять.
    _operaciya_s_oglavleniem(
        lambda: cache.put(path, stamp, engine.name, max_dim, lica,
                          dropped=otsortirovano), stats)
    stats.scanned += 1
    return lica


def scan_photos(files: Sequence[Path], engine: FaceEngine, cache: FaceCache, *,
                max_dim: int, should_stop: StopFn | None = None,
                on_progress: ProgressFn | None = None
                ) -> tuple[dict[Path, list[Face]], ScanStats]:
    """Возвращает лица по каждому фото и сводку. Ошибки не прерывают разбор.

    Отмена проверяется между фото: начатый снимок всегда доводится до конца и
    сохраняется в оглавление, чтобы следующий запуск продолжил с этого места.
    Прогресс отдаётся по каждому снимку, включая испорченные, — иначе полоска встаёт
    ровно там, где пользователю важнее всего её видеть.

    Порядок `files` важен: разбор идёт по списку, а не по алфавиту, так что папку
    можно обрывать на любом месте и продолжать с того же.

    Наружу функция отдаёт два именованных сбоя: `ModeliNeZagruzilis` (дело не дошло ни
    до одного снимка) и `OglavlenieNedostupno` (снимки до сбоя в оглавлении лежат).
    Вызывающий без Qt — пакетный прогон, например — получает их тем же текстом, что
    увидит человек.
    """
    stop = should_stop or (lambda: False)
    stats = ScanStats()
    result: dict[Path, list[Face]] = {}
    if not files:
        return result, stats           # грузить 300 МБ весов ради пустого списка незачем
    try:
        obespechit_zagruzku(engine)
    except ModeliNeZagruzilis:
        raise
    except Exception as exc:
        # Единственный сбой до первого снимка, и назвать его надо загрузкой: сказать
        # «оглавление недоступно» человеку без файла моделей — значит отправить его
        # чинить то, что не ломалось.
        raise ModeliNeZagruzilis(str(exc).strip() or type(exc).__name__) from exc
    # В сводку идёт прирост, а не общее число: оглавление живёт дольше разбора,
    # и его счётчик переживает и этот прогон, и следующие.
    povrezhdeniy_do = cache.damage_count
    t0 = time.perf_counter()
    total = len(files)
    for i, path in enumerate(files):
        if stop():
            break
        # Счётчики ведёт `_razobrat_foto`: он один знает, попадание это в оглавление,
        # свежий разбор или потерянный снимок. Вести те же счётчики снаружи значило бы
        # иметь два места, где `scanned` и `cached` способны разойтись.
        faces = _razobrat_foto(path, engine, cache, max_dim, stats)
        if faces is not None:
            result[path] = faces
        if on_progress:
            on_progress(i + 1, total, path)
    stats.cache_damage = cache.damage_count - povrezhdeniy_do
    stats.seconds = time.perf_counter() - t0
    return result, stats


class ScanWorker(QThread):
    """Разбор папки в рабочем потоке. Тяжёлое — никогда в потоке интерфейса.

    Сигналы уходят из рабочего потока, а слушает их интерфейс, поэтому соединение
    в Qt автоматически очерёдное: слот выполняется в потоке окна — только там и можно
    трогать виджеты.

    Прерванный разбор не теряется: после `request_stop()` `done` приходит с тем, что
    уже успели снять. Эти лица лежат и в оглавлении, значит следующий запуск
    продолжит с этого места, а не начнёт заново.

    Сбои прогона различаются текстом в `error` и только им: «не удалось загрузить
    модели» — ни один снимок не тронут, «оглавление недоступно» — снятое уже лежит в
    базе. По обоим путям `done` не приходит, поэтому интерфейс обязан на ошибке
    сохранить показанное, а не вычищать сетку: за этим в модуле следит тест
    `test_scan_worker_sboy_oglavleniya_ne_nazyvaetsya_sboyem_modeley`.
    """

    progress = Signal(int, int, str)      # обработано, всего, текущий файл
    done = Signal(object)                 # кортеж (dict[Path, list[Face]], ScanStats)
    error = Signal(str)

    def __init__(self, files: Sequence[Path], engine: FaceEngine, cache: FaceCache,
                 max_dim: int, parent: QObject | None = None) -> None:
        super().__init__(parent)
        self._files = list(files)
        self._engine = engine
        self._cache = cache
        self._max_dim = max_dim
        self._stop = False

    def request_stop(self) -> None:
        """Просьба остановиться. Вызывается из потока интерфейса.

        Гнаться за атомарностью нечем: присваивание булева — одна операция, а проверяется
        флаг только между фото, поэтому снимок, который уже в моделях, всё равно
        доводится до конца (см. `scan_photos`).
        """
        self._stop = True

    def run(self) -> None:
        try:
            # Модели загружаются внутри `scan_photos`, а не здесь: так загрузка
            # идёт под общим замком и второй прогон весов не трогает вовсе.
            photos, stats = scan_photos(
                self._files, self._engine, self._cache, max_dim=self._max_dim,
                should_stop=lambda: self._stop,
                on_progress=lambda d, t, p: self.progress.emit(d, t, p.name),
            )
            self.done.emit((photos, stats))
        except (ModeliNeZagruzilis, OglavlenieNedostupno) as exc:
            # Формулировка собрана на месте события, где известно, что терялось, а что
            # нет. Здесь её нельзя ни переписывать, ни склеивать с «распознавание не
            # запустилось»: интерфейс показывает эту строку как есть.
            self.error.emit(str(exc))
        except Exception as exc:            # падение разбора — не падение приложения
            # «Не знаю почему» не должно притворяться известным этапом: иначе задача 15
            # снова начнёт винить модели в том, что модели и не трогали.
            self.error.emit(f"разбор прервался: {exc}")
