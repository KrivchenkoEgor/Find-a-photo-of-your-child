"""Разбор папки в фоне: тяжёлая работа никогда не идёт в потоке интерфейса.

Модуль нарочно разрезан надвое. `scan_photos` — чистая функция без Qt: она принимает
список файлов, движок и оглавление и возвращает лица вместе со сводкой. Именно её
покрывают тесты, её же сможет вызвать пакетный прогон без всякого окна.
`ScanWorker` — тонкая `QThread`-обёртка над ней: переносит работу в другой поток и
превращает вызовы обратного вызова в сигналы.

Три обещания, которые держит этот модуль.

1. Модели читаются один раз на сессию, а не на прогон: см. `obespechit_zagruzku`.
2. Отброшенная работа видна числом: испорченный снимок, упавшая модель, лицо с
   непригодным отпечатком и выброшенная строка оглавления оставляют след в `ScanStats`,
   а не исчезают молча — отчёт (задача 10) различает «не читается» и «лицо отброшено».
3. Отмена проверяется между фото. Начатый снимок доводится до конца и записывается
   в оглавление, чтобы следующий запуск продолжил с этого места, а не начал заново.

Сбой всего разбора — беда отдельная, и лиц у неё ровно два. Не поднялись веса:
распознавание не начиналось, ни один снимок не читался. Умерла база посреди прогона:
снять успели столько-то, и снятое лежит в оглавлении. Эти два случая различаются типом
исключения (`ModeliNeZagruzilis`, `OglavlenieNedostupno`) и уже собранным текстом —
рабочий поток отдаёт его интерфейсу как есть, задача 15 не придумывает ему заголовок.
"""

