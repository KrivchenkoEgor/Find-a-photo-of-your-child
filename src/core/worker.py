# Один замок на все движки: `load()` у `BothEngine` не атомарен (проверяет флажок,
# потом 13–21 с грузит `FaceAnalysis`), и два потока, решившие «движок не готов»
# одновременно, собрали бы веса дважды — а второй заход ещё и падает на
# `adopt_recognition()` уже после того, как модели прочитаны.
_zagruzochnyy_zamok = threading.Lock()

_T = TypeVar("_T")


def _mnohozhechestvo(n: int, odin: str, mala: str, mnogo: str) -> str:
    """Форма существительного по числу: «1 снимок», «2 снимка», «5 снимков», «21 снимок».

    Разбитая согласованность с числом — это то, что родитель замечает в тексте ошибки
    раньше самого текста. Глаголы при таком числе лучше не ставить вовсе: «21 снимок
    лежат» звучало бы уже хуже, чем цифра без глагола.
    """
    if 11 <= n % 100 <= 14:
        return mnogo
    poslednyaya = n % 10
    if poslednyaya == 1:
        return odin
    if 2 <= poslednyaya <= 4:
        return mala
    return mnogo


# Сырая строка SQLite родителю бесполезна: «database or disk is full» не подсказывает,
# что делать. Известные сбои переводим в действие, неизвестные отдаём как есть — пусть
# в тексте ошибки останется хотя бы то, что можно скопировать в письмо поддержке.
_SBBOI_OGLAVLENIYA: tuple[tuple[str, str], ...] = (
    ("disk is full", "на диске закончилось свободное место — освободите его"),
    ("disk full", "на диске закончилось свободное место — освободите его"),
    ("no space left", "на диске закончилось свободное место — освободите его"),
    ("disk i/o error", "диск не отвечает — возможно, внешний диск или флешку отсоединили"),
    ("i/o error", "диск не отвечает — возможно, внешний диск или флешку отсоединили"),
    ("database is locked", "оглавление занято другой копией программы — закройте её"),
    ("readonly database", "файл оглавления закрыт для записи — проверьте права на папку"),
    ("read-only database", "файл оглавления закрыт для записи — проверьте права на папку"),
    ("unable to open database file",
     "файл оглавления не открывается — проверьте, что диск на месте"),
    ("file is not a database",
     "файл оглавления повреждён — очистите его в настройках, папку разберёт заново"),
    # Настоящая строка SQLite про испорченный файл базы (`SQLITE_CORRUPT`). Прежний ключ
    # держил формулировку «database is corrupted», которой SQLite не говорит никогда:
    # битое оглавление проваливалось в общий ответ «база не отвечает», и человек терял
    # ровно тот совет, ради которого строка заведена, — очистить оглавление.
    ("database disk image is malformed",
     "файл оглавления повреждён — очистите его в настройках, папку разберёт заново"),
    ("file is encrypted", "файл оглавления зашифрован и приложению недоступен"),
)


def _obyasni_sbboy_oglavleniya(exc: BaseException) -> str:
    """Одна русская фраза с действием вместо сырой строки SQLite или OSError."""
    stoka = str(exc).strip().lower()
    for priznak, formulirovka in _SBBOI_OGLAVLENIYA:
        if priznak in stoka:
            return formulirovka
    return f"база оглавления не отвечает ({exc})"


class ModeliNeZagruzilis(RuntimeError):
    """Веса не поднялись: распознавание не начиналось, терялось нечего.

    Отдельный тип нужен ради одного слова в тексте. Сказать «оглавление недоступно»
    человеку, у которого просто нет файла моделей, — значит отправить его чинить то,
    что не ломалось. Задача 15 печатает `str(exc)` как есть: этап уже назван здесь.

    «Путь к моделям» — это НЕ настройка: в полосе настроек её нет и быть не должно,
    человек туда не смотрит. Поэтому текст называет оба настоящих пути прямо — их
    печатают геттеры `utils.config`, те же самые, по которым приложение и ходит.
    Один путь лежит внутри самого приложения и весит 230 КБ, второй качается при
    первом запуске и весит ~290 МБ; это две разные беды и два разных действия.

    Пути собираются лениво и в `try`: сообщение об отсутствующих весах не имеет права
    само падать — человек увидел бы traceback вместо объяснения, что делать.
    """

    def __init__(self, prichina: str) -> None:
        self.prichina = prichina
        super().__init__(
            f"не удалось загрузить модели: {prichina}\n\n"
            "Распознавание не начиналось: ни один снимок не разобран.\n"
            "Приложению нужны два файла, и живут они в двух разных местах:\n"
            f"  • поиск лиц, 230 КБ, лежит внутри приложения:\n{_put_yuneta()}\n"
            f"  • распознавание лиц, около 290 МБ, скачивается при первом запуске:\n"
            f"{_puta_buffalo()}\n"
            "Если вторая папка пуста или её нет — закачка оборвалась: нужен интернет "
            "и ~300 МБ свободного места на диске. После починки перезапустите "
            "приложение: оно попробует скачать заново."
        )


