"""Копирование отмеченных фото. Ничего существующего не затираем.

Модуль живёт в конце пути: он пишет в папку, которую выбрал человек, и обычно это
папка с семейными снимками. Одна перезапись там невосстановима, поэтому единственная
разрешённая реакция на занятое имя — новое имя (`a.jpg` → `a_1.jpg`), а не
`shutil.copyfile` поверх.

Порядок обхода списка задаёт вызывающий: пары возвращаются в том же порядке, в каком
копировались файлы, и именно этот порядок потом читается в отчёте.

Второе обещание дороже первого: один плохой файл не имеет права стоить всей пачки.
Снимок мог удалиться между разбором папки и копированием, мог оказаться без прав на
чтение, мог упереться в полное место на диске или в имя, которое не вмещается в
бюджет файловой системы. Всё это — `OSError`, и ловим мы его для каждого файла
отдельно: прогон доходит до конца списка, а потеря названа файлом и причиной.

Названа — буквально: причина уходит вызывающим обязательным аргументом, а усечённый
на ползаписи снимок убирается с диска. Человек не должен находить его в папке
результатов раньше, чем прочтёт в отчёте.
"""

from __future__ import annotations

import os
import shutil
from pathlib import Path
from typing import Sequence

# Предел одного имени файла для тома, который о себе не рассказал. `os.pathconf`
# спрашивает у конкретного тома: у APFS, ext4 и NTFS это 255, но сетевые шары и
# старые флешки называют и меньше. В каких единицах том считает свои 255 — см.
# `_predel_imeni`: на кириллическом имени это разница ровно вдвое.
_IMYA_PREDIEL = 255

# Резерв под счётчик вариантов: имя со счётчиком режут так, чтобы `stem_999.jpg` всё
# ещё влезал. Откусывают его только тому имени, которое уже столкнулось с занятым
# местом, — первое свободное имя берёт весь бюджет целиком (см. `unique_dest`).
# Разряд счётчик прибавляет на тысяче занятых имён — там диск откажет сам, этот
# файл уйдёт в потери, а пачка дойдёт до конца.
_REZERVE_PDSCHETCHIKA = 4


def _predel_imeni(dest_dir: Path) -> int:
    """Сколько том отводит под одно имя файла в этой папке.

    Спрашиваем у самого диска: `PC_NAME_MAX` различается у локального тома, сетевого
    шара и флешки, и угадать его нельзя. Имя константы передаём строкой: числовые
    `os.PC_*` есть не на всех платформах (на macOS их нет вовсе), а строку принимает и
    Linux, и macOS. Папки ещё нет, том не отвечает, `pathconf` не существует
    (Windows) — берём общий предел: он почти везде не больше реального и никогда не
    обещает лишнего.

    Меру ответа том не сообщает, а она на трёх томах разная: APFS и HFS+ считают
    символы — проверено на этом томе, 251 кириллическая `ю` плюс `.jpg` (506 байт)
    диск принимает, а 259 латинских байтов в 259 символах уже отказывает;
    `File name too long` в обоих случаях отдаёт ровно один и тот же `Errno 63`. NTFS
    считает единицы UTF-16, и только ext4 считает байты. Поэтому весь модуль дальше
    держит бюджет в байтах: это наихудшая из трёх мер, и имя, вписанное в неё, не
    откажет ни одному тому. Плата за это — кириллическое имя на пределе на macOS
    урежется вдвое раньше, чем потребовал бы том.
    """
    pathconf = getattr(os, "pathconf", None)
    if pathconf is None:
        return _IMYA_PREDIEL
    try:
        predel = int(pathconf(dest_dir, "PC_NAME_MAX"))
    except (OSError, ValueError, NotImplementedError):
        return _IMYA_PREDIEL
    return predel if predel > 0 else _IMYA_PREDIEL


def _obryzat(text: str, predel: int) -> str:
    """Текст не длиннее `predel` байт; режем по границе символа, а не байта.

    Мера — байты, хотя локальные томы macOS и Windows считают символы (см.
    `_predel_imeni`): байт — единственная мера, с которой согласны все три тома, и имя,
    вписанное в неё, не откажет никто. На кириллическую `ю` уходит два байта, поэтому
    такое имя вдвое короче предела, хотя на глаз кажется коротким. Бинарный поиск, а не
    цикл по символу, чтобы длинное имя не перекодировать сотни раз.
    """
    if predel <= 0:
        return ""
    if len(os.fsencode(text)) <= predel:
        return text
    niz, verh = 0, len(text)
    while niz < verh:
        sred = (niz + verh + 1) // 2
        if len(os.fsencode(text[:sred])) <= predel:
            niz = sred
        else:
            verh = sred - 1
    return text[:niz]


def _sokrat(stem: str, suffix: str, predel: int) -> tuple[str, str]:
    """Стем и суффикс, чьё имя вместе вписывается в бюджет `predel` байт.

    Бюджет передаёт вызывающий, и в этом весь смысл: имя, которому не с чем
    сталкиваться, получает все 255, а вариант со счётчиком — на `_REZERVE_PDSCHETCHIKA`
    меньше, чтобы `stem_999.jpg` влез всегда. Резерв, откушенный заранее, резал бы и
    первое имя, — половина имени снимка терялась бы там, где сталкиваться не с чем.

    Суффикс бережём: по нему человек опознаёт снимок и в отчёте, и в папке результатов;
    трогать его приходится только у имени, где «расширение» само вышло длиннее бюджета.
    """
    razmer = len(os.fsencode(suffix))
    if razmer >= predel:
        suffix = _obryzat(suffix, max(predel // 2, 0))
        razmer = len(os.fsencode(suffix))
    return _obryzat(stem, max(predel - razmer, 0)), suffix


def unique_dest(dest_dir: Path, name: str) -> Path:
    """Свободное имя в папке результатов: a.jpg → a_1.jpg → a_2.jpg.

    Проверка идёт по диску, а не по памяти, поэтому два одноимённых снимка из разных
    папок архива получают разные места, даже если вызывающий позвал `copy_photos`
    один раз. Суффикс нарастает от исходного имени: `a_1.jpg` занят → `a_1_1.jpg`,
    как в `copy_with_unique_name` из эталонного скрипта.

    Возвращаемое имя всегда вписано в бюджет тома (см. `_predel_imeni`): здесь не бывает
    `File name too long` — в том числе на длинных кириллических именах, которых в
    семейном архиве много. Целое имя без запаса получает только первое свободное место:
    как только пришлось звать счётчик, бюджет ужимается на `_REZERVE_PDSCHETCHIKA`,
    чтобы и `stem_999.jpg` влез.
    """
    dest_dir = Path(dest_dir)
    stem, suffix = Path(name).stem, Path(name).suffix
    predel = _predel_imeni(dest_dir)
    stem, suffix = _sokrat(stem, suffix, predel)
    candidate = dest_dir / (stem + suffix)
    n = 1
    while True:
        try:
            if not candidate.exists():
                return candidate
        except OSError:
            # Бюджет имени соблюдён, поэтому сюда доходит только настоящая беда тома
            # (отвалился сетевой диск). Гадать дальше незачем: пусть скажет о ней
            # `shutil.copy2` — у неё будет настоящая причина, а не враньё про занятое
            # имя. Вызывающий поймает и запишет снимок в потери.
            raise
        if n == 1:
            # Столкновение: дальше к имени прибавляется `_N`, и резерв под счётчик
            # оплачивает уже это имя, а не первое. Урезка только укорачивает, поэтому
            # ни одно ранее предложенное имя сюда не вернётся.
            stem, suffix = _sokrat(stem, suffix, predel - _REZERVE_PDSCHETCHIKA)
        candidate = dest_dir / f"{stem}_{n}{suffix}"
        n += 1


def copy_photos(files: Sequence[Path], dest_dir: Path,
                poteri: list[tuple[Path, str]]) -> list[tuple[Path, Path]]:
    """Копирует и возвращает пары (откуда, куда) — это идёт в отчёт.

    Папку создаём сами: вызывающий указывает существующую, но вложенной папки
    результатов у него может и не быть.

    Каждый файл изолирован `try/except OSError`, и это не косметика: ради одного
    пропавшего файла терять остальные двести нельзя. Снимок удалили между разбором
    папки и копированием — прогон идёт дальше; нет прав на чтение — дальше; кончилось
    место на диске — остальные снимки всё равно доедут до папки результатов.

    Сколько потеряно — видно по числу пар: вызывающий сверяет `len(pairs)` с числом
    отмеченных, и это главный канал, он был и остаётся. Почему именно потеряно —
    второй канал, `poteri`: в переданный вызывающим список кладём пару (файл,
    причина), и она годится прямо в раздел потерь `write_report`. Аргумент обязателен,
    и не из вредности: необязательным он жил бы на честном слове вызывающего, а вызов
    без него выглядит совершенно правильно и молчит — человек видит честное
    «скопировано 0 фото» без единого слова о том, что случилось. Список передают, а не
    получают в return, потому что контракт возврата `list[(src, dst)]` зафиксирован
    планом задачи 15 (`pairs = copy_photos(...)`, следом `copied=pairs`, `len(pairs)`
    и `for s, d in pairs`): третий элемент разорвал бы каждый из этих трёх способов
    обратиться к парам.

    `ValueError`, `MemoryError` и прочее не глотаем: это не беда одного снимка, а
    поломка прогона, и молчать о ней нельзя.
    """
    dest_dir = Path(dest_dir)
    dest_dir.mkdir(parents=True, exist_ok=True)
    pairs: list[tuple[Path, Path]] = []
    for src in files:
        src = Path(src)
        if not src.is_file():
            poteri.append((src, "файл недоступен: снимка нет на диске"))
            continue
        try:
            dst = unique_dest(dest_dir, src.name)
        except OSError as exc:
            # Имени ещё нет: убирать нечего и не за чем — усечённого файла этот
            # сбой не оставляет, и лезть в `unlink` по несуществующему пути нельзя.
            poteri.append((src, f"копирование не удалось: {exc}"))
            continue
        try:
            # copy2, а не copyfile: дата съёмки дороже экономии
            shutil.copy2(src, dst)
        except OSError as exc:
            prichina = f"копирование не удалось: {exc}"
            # copy2 пишет частями и за собой не убирает: после `ENOSPC` или `EIO` в
            # папке результатов остаётся усечённый снимок. В `pairs` его нет, значит
            # в разделе «Скопировано» он не значится и человек о нём не узнает.
            # Убираем сами: `unique_dest` отдал это имя как свободное, а значит снять
            # можем свою незаконченную запись, а не чужой файл. Не удалось убрать —
            # это сказано прямо в причине: половина снимка осталась в папке, и о ней
            # надо знать, а не находить её глазами.
            try:
                dst.unlink(missing_ok=True)
            except OSError as uborka:
                prichina += f"; оборванный снимок остался в папке: {uborka}"
            poteri.append((src, prichina))
            continue
        pairs.append((src, dst))
    return pairs
