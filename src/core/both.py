"""Режим «Оба»: два детектора, одно множество лиц.

Быстрый YuNet один на 20 подтверждённых фото даёт 19: на одном он насчитал 28%
против 45% у InsightFace. Порогом это не лечится, поэтому берём максимум с двух
наборов лиц — так находится всё, что нашёл любой из них.

Здесь же живёт разделение модели распознавания: оба движка просят одну и ту же
arcface из buffalo_l, и второй её копии в памяти быть не должно.
"""

from __future__ import annotations

from typing import Any, Sequence

import numpy as np

from .engine import Face, FaceEngine

OVERLAP = 0.5    # выше этого две рамки считаются одним и тем же лицом


def iou(a: Face, b: Face) -> float:
    """Пересечение рамок относительно ПЛОЩАДИ МЕНЬШЕЙ из них.

    Обычный IoU (через объединение) подводит, когда одно лицо внутри другого:
    вложенная мелкая рамка даёт малый IoU и дублирует то же лицо. Рамка 20×20
    внутри 100×100 — это классические 0.04, и при таком измерении одно и то же
    лицо ребёнка прошло бы вторым лицом. Относительно меньшей рамки это 1.0.
    """
    ax1, ay1, ax2, ay2 = a.box
    bx1, by1, bx2, by2 = b.box
    ix = max(0.0, min(ax2, bx2) - max(ax1, bx1))
    iy = max(0.0, min(ay2, by2) - max(ay1, by1))
    inter = ix * iy
    if inter <= 0.0:
        return 0.0
    small = min((ax2 - ax1) * (ay2 - ay1), (bx2 - bx1) * (by2 - by1))
    return inter / small if small > 0 else 0.0


def merge_faces(primary: Sequence[Face], secondary: Sequence[Face],
                overlap: float = OVERLAP) -> list[Face]:
    """Сливает два набора лиц в один: одно лицо — одна рамка, и рамка крупнее.

    `primary` считается основным: при равных размерах выживает он, а не кандидат,
    и порядок обхода именно такой — сначала primary, потом secondary.

    Через цикл коллизий проходят ВСЕ лица, и из primary тоже. Раньше `kept`
    начинался с `list(primary)`, то есть лица одного детектора между собой не
    сверялись: вложенная рамка внутри крупной давала то же лицо дважды, а кандидат,
    столкнувшийся с обеими, ставился в первую совпавшую позицию и дублировал вторую
    — при этом отпечаток меньшей рамки исчезал молча. Детекторные NMS от этого не
    спасают: они давят рамки по IoU (0.4), а вложенная рамка при пересечении
    относительно меньшей даёт 1.0 и проходит.

    Если рамки совпали, оставляем ту, что больше: крупная рамка = больше пикселей
    на отпечаток. `size` — меньшая сторона рамки, и для лиц это верный размер: он же
    решает, пройдёт ли лицо фильтр `min_face` в движке. Считать площадь нельзя: узкая
    полоса 100×10 обогнала бы по площади настоящее лицо 30×30, а пикселей на
    отпечаток в ней меньше.

    Инвариант, который держит этот цикл: в результате любые две рамки между собой не
    совпадают (`iou` не выше порога). Поэтому кандидат, крупнее которого среди
    оставленных уже есть, отбрасывается целиком, а кандидат крупнее всех совпавших
    с ним заменяет их все — иначе одна большая рамка, лёгшая поверх двух маленьких,
    оставила бы после себя дубль.

    Порядок возврата — по левому верхнему углу, чтобы интерфейс показывал лица
    одинаково от прогона к прогону.
    """
    kept: list[Face] = []
    for cand in (*primary, *secondary):
        clash = [i for i, p in enumerate(kept) if iou(p, cand) > overlap]
        if not clash:
            kept.append(cand)
            continue
        if cand.size <= max(kept[i].size for i in clash):
            continue                                # он и есть уже оставленное лицо
        clash_set = set(clash)
        kept = [p for i, p in enumerate(kept) if i not in clash_set] + [cand]
    return sorted(kept, key=lambda f: (f.x1, f.y1))


class BothEngine:
    """Сначала InsightFace, потом YuNet; лица двух детекторов сливаются в один список.

    Отпечатки обоих наборов уходят в `matcher`, и он берёт максимум — так не теряется
    то единственное фото, где один из детекторов лицо не нашёл.
    """

    name = "both"

    def __init__(self, yunet: FaceEngine, insight: FaceEngine) -> None:
        self._yunet = yunet
        self._insight = insight
        self._zagruzheno = False

    @property
    def loaded(self) -> bool:
        """Готов ли движок: подняты оба пути.

        Держится на `_zagruzheno`, который `load()` ставит только после успешного
        прохождения обоих движков: «не готово» здесь честное, и неудачную попытку
        можно повторить.
        """
        return self._zagruzheno

    def load(self) -> None:
        """Идемпотентно: сколько бы раз ни позвали, веса читаются один раз.

        Рабочий поток (задача 9) вообще старается не звать повторно и сверяется с
        `loaded`, но полагаться только на это нельзя: второй `load()` вправе вызвать
        и интерфейс, и пакетный прогон, и следующий движок в цепочке.

        Без флага второй вызов стоил бы 13–21 с на пересборку `FaceAnalysis` и кончался
        бы исключением RuntimeError: `insight.load()` отдаёт новый объект распознавателя,
        юнет принимает его только до своей загрузки, и на втором круге
        `adopt_recognition()` падает уже после того, как модели прочитаны. Сообщение про
        «распознаватель подставляют до load()» пользователь не может ни понять, ни
        применить.

        Флаг ставится только после успешного прохождения обоих движков: если
        распознавание не поднялось, следующая попытка имеет право начаться заново.
        """
        if self._zagruzheno:
            return
        self._insight.load()          # buffalo_l одна и та же, грузим первой
        self._podelit_razpoznavanie()
        self._yunet.load()
        self._zagruzheno = True

    def _podelit_razpoznavanie(self) -> None:
        """Отдать юнету распознаватель, который InsightEngine уже загрузил.

        Без разделения режим «Оба» стоил бы двойной памяти: w600k_r50 на 174 МБ
        легла бы в процесс дважды, потому что FaceAnalysis грузит её сам и общий кэш
        `_load_recognition()` при этом не заполняет.

        Проверка через `getattr`, а не прямые обращения: здесь могут лежать любые
        `FaceEngine`, и у чужой реализации ни `recognition_model`, ни
        `adopt_recognition` не предусмотрено. Тогда юнет грузит распознаватель сам,
        как и до появления этого режима.
        """
        model: Any = getattr(self._insight, "recognition_model", None)
        adopt = getattr(self._yunet, "adopt_recognition", None)
        if model is None or adopt is None:
            return
        # Контракт разделения: и FaceAnalysis, и `_load_recognition()` готовят модель с
        # ctx_id=-1, то есть на CPU. Самого ctx_id insightface 2.0 у модели не хранит,
        # поэтому проверяем то, что из него следует, — провайдеров сессии ONNX Runtime.
        # Другой набор значил бы, что юнету отдают сеть, подготовленную под GPU: её
        # молча разделять нельзя, у двух путей разные требования к контексту.
        sessiya = getattr(model, "session", None)
        if sessiya is not None:
            assert "CPUExecutionProvider" in sessiya.get_providers(), \
                "разделённая модель подготовлена не на CPU"
        adopt(model)

    def detect(self, image: np.ndarray) -> list[Face]:
        return merge_faces(self._insight.detect(image), self._yunet.detect(image))

    @property
    def otsortirovannye_lica(self) -> int:
        """Отбраковка обоих путей одним числом — сводка разбора читает именно движок.

        Слишком крупные дубли, которые сворачивает `merge_faces`, сюда не входят:
        это то же самое лицо, найденное дважды, а не потерянные данные.
        """
        return sum(getattr(dvizhok, "otsortirovannye_lica", 0)
                   for dvizhok in (self._insight, self._yunet))
