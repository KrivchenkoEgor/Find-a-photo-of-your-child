"""Как нарисовать лицо карточкой: кроп, конвертация в QPixmap, номер на кадре.

Модуль не спрашивает и не решает. Он отвечает на один вопрос — как показать найденное
лицо так, чтобы человек его узнал. Спрашивает «какое лицо искать» окно эталона
(`ui/reference_dialog.py`), показывает находки сетка результатов (`ui/results_view.py`),
и обе рисуют одними и теми же функциями отсюда.

Раньше здесь же жил `FacePickerDialog` — «найди лицо на одном снимке». Его заменило окно
эталона: там карточек столько, сколько человек принёс файлов, и они переживают несколько
партий добавления. Оставлять второй вариант того же диалога значило бы однажды развести
две сетки лиц вручную.

Здесь нет ни моделей, ни чтения файлов: картинку и список лиц приносят снаружи
(`scanner.load_photo` и движок распознавания). Отпечатки лиц не используем и не показываем:
человеку они ничего не говорят, а слово, которым их называют, в интерфейсе запрещено.

Два места, где молча ломается разметка карточек:

* рамка лица лезет за край снимка — кроп режем по границе кадра и держим его квадратным
  по центру рамки, иначе на узком высоком лице в карточку попадает четверть лица;
* кадр тёмный или однотонный — все кропы на нём одинаковые, поэтому номер рисуем прямо
  на карточке, а не только подписью под ней.
"""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass

import cv2
import numpy as np
from PySide6.QtGui import QImage, QPixmap

from core.engine import Face

PAD = 0.35        # расширяем рамку, чтобы было видно причёску и плечи
STORONA_KARTOKI = 160

# Рамка найденного лица: тот же цвет и та же толщина и в сетке результатов, и в окне
# просмотра. Единственный владелец — этот модуль: два места с одним «как выглядит лицо»
# однажды разъезжаются, и человек перестаёт понимать, какой из двух прямоугольников
# чему соответствует.
ZELENYJ = (0, 255, 0)
TOLSHCHINA_RAMKI = 2

# Красный в этом проекте значит ровно одно: «это НЕ то, что мы ищем». Рамка найденного
# лица в результатах им не рисуется — там отсутствие рамки и есть ответ. Он нужен там,
# где у человека спрашивают решение, а состояние галочки он не видит: квадратик отметки
# на сетке из двадцати карточек глазом не находится.
RAMKA_KRASNYJ = (0, 0, 255)


def obvesti(kadr: np.ndarray, tsvet: Sequence[int], storona: int = 4) -> np.ndarray:
    """Рамка по краю всего кадра. Возвращает КОПИЮ.

    Нужна там, где состояние карточки обязаны видеть глазами, а не ища галочку: цвет
    вдоль края невозможно пропустить, а `cv2.rectangle` режет её по границе сам.
    """
    risunok = kadr.copy()
    vysota, shirina = risunok.shape[:2]
    do = max(0, min(storona, vysota // 2, shirina // 2)) - 1
    return cv2.rectangle(risunok, (0, 0), (shirina - 1, vysota - 1), tuple(int(c) for c in tsvet),
                         do + 1)

@dataclass(frozen=True)
class RamkaLica:
    """Одно лицо на показываемом снимке: рамка и её номер.

    Тип живёт здесь, а не в окне просмотра, потому что рамки рисуют три поверхности:
    сетка находок, окно находок и окно выбора эталона. `nomer` считается с единицы и
    обязан совпадать с подписью («лицо 2 из 3»), иначе рамка на крупном кадре не свяжется
    с тем, что человек кликнул.
    """

    box: Sequence[float]
    nomer: int

# Меньшая сторона рамки в пикселях. Число не косметика: подпись под сеткой отправляет
# человека решать «моё / не моё» по этой рамке, и рамка, которой на экране не видно,
# обещание ломает. Замер на архиве проекта: на 55 из 147 фото меньшая сторона после
# пересчёта в миниатюру выходила 5…13 px. 16 px — нижняя граница читаемости на
# миниатюре 220 px. Лица крупнее порога не трогаются вовсе — см. `ramka_na_kadr`.
MIN_RAMKA_PX = 16


def ramka_na_kadr(kadr: np.ndarray, box: Sequence[float], k: float = 1.0,
                  storona_min: int = MIN_RAMKA_PX, nomer: int = 0) -> np.ndarray:
    """Зелёная рамка найденного лица поверх кадра. РИСУЕТ НА МЕСТЕ — передавайте копию.

    `k` — во сколько раз показанный кадр мельче того, в пикселях которого пришла рамка.
    Сетка результатов умножает на `220 / 2400`, окно просмотра читает кадр в том же
    разрешении, что и модели, и приносит единицу.

    `nomer` (с единицы) подписывает рамку тем же кружком, что и карточку лица. Нужен там,
    где на снимке рамок несколько: без номера человек не свяжет рамку с карточкой
    «лицо 2 из 3». 0 — не подписывать.

    Мелкое лицо дорастает до `storona_min` вокруг своего ЦЕНТРА. Без этого на трети
    архива рамки просто не видно, а без центра рамка врёт о месте лица не меньше, чем
    о его размере. Крупные лица не трогаются: на них размер рамки это размер лица, и
    раздуть его значило бы наврать про то, насколько крупно ребёнок в кадре.

    За край кадра рамка не вылезает: `cv2.rectangle` режет её сам, и это надёжнее
    ручного пересечения.
    """
    x1, y1, x2, y2 = (int(v * k) for v in box[:4])
    storona = max(x2 - x1, y2 - y1)
    if storona < storona_min:
        # +1 на нечётную разницу: сторона может стать больше на единицу, меньше — нельзя
        dozvor = (storona_min - storona + 1) // 2
        x1, y1, x2, y2 = x1 - dozvor, y1 - dozvor, x2 + dozvor, y2 + dozvor
    narisovannyj = cv2.rectangle(kadr, (x1, y1), (x2, y2), ZELENYJ, TOLSHCHINA_RAMKI)
    if nomer:
        # кружок в углу рамки и обязательно внутри кадра: подпись, уехавшая за край,
        # превращает номер в «непонятно, куда смотреть»
        krug = max(10, min(24, max(x2 - x1, y2 - y1) // 3))
        tsentr = (max(krug, min(x1 + krug + 1, narisovannyj.shape[1] - krug - 1)),
                  max(krug, min(y1 + krug + 1, narisovannyj.shape[0] - krug - 1)))
        krug_s_cifroj(narisovannyj, tsentr, krug, nomer)
    return narisovannyj


def ramki_na_kadr(kadr: np.ndarray, ramki: Sequence[RamkaLica], k: float = 1.0) -> np.ndarray:
    """Рамки со номерами на перечисленных лицах. РИСУЕТ НА МЕСТЕ — передавайте копию.

    Одна функция на три поверхности: карточку сетки, окно находок и окно выбора эталона.
    ЧТО рисовать решает вызывающий — он приносит список, — а как он выглядит, решает
    этот модуль. Разойтись в том и другом было бы тем самым «превью врёт про находку».
    """
    for ramka in ramki:
        ramka_na_kadr(kadr, ramka.box, k, nomer=ramka.nomer)
    return kadr


def _ramka_kadra(box: Sequence[float], vysota: int, shirina: int) -> tuple[int, int, int]:
    """Квадрат (верх, лево, сторона) в пикселях кадра под карточку этого лица.

    Рамка лица с запасом `PAD` почти никогда не влезает в снимок целиком: у края кадра
    запас обрезается. Квадрат берём по центру оставшегося, иначе вытянутое лицо режется «от
    верхнего левого угла» и в карточку попадает четверть лица. Сторона 0 — рамка легла
    целиком мимо кадра: это не исключение, а повод показать заглушку.
    """
    x1, y1, x2, y2 = box
    zapas = max(x2 - x1, y2 - y1) * PAD
    lev = max(0, int(x1 - zapas))
    verx = max(0, int(y1 - zapas))
    prav = min(shirina, int(x2 + zapas))
    niz = min(vysota, int(y2 + zapas))
    vys, shir = niz - verx, prav - lev
    if vys <= 0 or shir <= 0:
        return 0, 0, 0
    storona = min(vys, shir)
    # квадрат по центру обрезанной рамки: при равенстве сторон сдвиг нулевой
    return verx + (vys - storona) // 2, lev + (shir - storona) // 2, storona


def krop_po_ramke(image: np.ndarray, box: Sequence[float],
                  side: int = STORONA_KARTOKI) -> np.ndarray:
    """Квадратный кроп вокруг ОДНОЙ рамки лица.

    Нужен не только списку лиц: окно просмотра фото (задача T10) получает из строки
    результатов одну рамку, а не объект `Face`, и строить для него фейковое лицо
    значило бы изобретать тип ради вызова функции.
    """
    vysota, shirina = image.shape[:2]
    verx, lev, storona = _ramka_kadra(box, vysota, shirina)
    if storona <= 0:
        # лицо целиком вне кадра: заглушка вместо падения, карточка останется на месте
        return np.zeros((side, side, 3), dtype=np.uint8)
    crop = image[verx:verx + storona, lev:lev + storona]
    return cv2.resize(crop, (side, side), interpolation=cv2.INTER_AREA)


def crops_from(image: np.ndarray, faces: Sequence[Face],
               side: int = STORONA_KARTOKI) -> list[np.ndarray]:
    """Квадратные кропики лиц для показа. Рамку расширяем и режем по краю кадра.

    `image` — BGR-массив из `load_photo`, `faces` — лица того же снимка. Порядок результата
    совпадает с порядком `faces`: карточка обязана соответствовать своему лицу, иначе
    «второе слева» приведёт не к тому отпечатку.
    """
    return [krop_po_ramke(image, lic.box, side) for lic in faces]


def face_to_qpixmap(img: np.ndarray) -> QPixmap:
    """BGR-кадр OpenCV -> QPixmap.

    Два места, о которые это обычно спотыкается:

    * QImage данными не владеет. Без `.copy()` он смотрел бы в массив numpy, который живёт
      до конца функции, и на экране замаячил бы мусор;
    * для `Format_RGB888` Qt требует длину строки, кратную четырём байтам, а у честного
      BGR-кадра там `3 * ширина` — не кратно при каждой второй ширине. Реальный снимок из
      телефона ровно такой и есть. На этой сборке PySide6 кривая строка проходит молча, но
      держать под рукой формат, который по документации ловить нечем, значит однажды
      получить пустые карточки; шаг строки выравниваем нулями справа, пиксели не съезжают.

    Функция публичная не только ради этого диалога: миниатюры сетки результатов (задача 14)
    обязаны импортировать её, а не собирать `QImage` из буфера numpy заново.
    """
    rgb = np.ascontiguousarray(cv2.cvtColor(img, cv2.COLOR_BGR2RGB))
    vysota, shirina = rgb.shape[:2]
    shag = 3 * shirina
    bufer = rgb
    if shag % 4:
        rovnyj_shag = ((shag + 3) // 4) * 4
        stroki = np.zeros((vysota, rovnyj_shag), dtype=np.uint8)
        stroki[:, :shag] = rgb.reshape(vysota, shag)
        bufer, shag = stroki, rovnyj_shag
    q = QImage(bufer.data, shirina, vysota, shag, QImage.Format.Format_RGB888)
    return QPixmap.fromImage(q.copy())


def krug_s_cifroj(kadr: np.ndarray, tsentr: tuple[int, int], krug: int, nomer: int) -> None:
    """Чёрный кружок с белой цифрой. РИСУЕТ НА МЕСТЕ — вызывающий решает, копия ли.

    Общий для карточки лица и для подписи рамки на крупном снимке: два способа
    нарисовать номер однажды станут двумя разными номерами, и человек перестанет
    понимать, какое «лицо 2» он видит.
    """
    cv2.circle(kadr, tsentr, krug, (0, 0, 0), cv2.FILLED)
    cv2.circle(kadr, tsentr, krug, (255, 255, 255), 1)
    tekst = str(nomer)
    sherift, masshtab = cv2.FONT_HERSHEY_SIMPLEX, krug / 12.0
    tolshchina = max(1, krug // 7)
    (shir, vys), _ = cv2.getTextSize(tekst, sherift, masshtab, tolshchina)
    cv2.putText(kadr, tekst, (tsentr[0] - shir // 2, tsentr[1] + vys // 2), sherift,
                masshtab, (255, 255, 255), tolshchina, cv2.LINE_AA)


def naklej_nomer(kadr: np.ndarray, nomer: int) -> np.ndarray:
    """Номер прямо на снимке лица.

    Подпись под карточкой человек не читает, когда карточек пять, а «второе слева» надо
    тыкнуть. Чёрный кружок с белой цифрой остаётся читаемым и на светлом, и на тёмном
    кадре; на совершенно чёрном снимке — единственный способ различить карточки.
    """
    risunok = kadr.copy()
    krug = max(12, risunok.shape[0] // 5)
    krug_s_cifroj(risunok, (krug + 3, krug + 3), krug, nomer)
    return risunok
